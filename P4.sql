-- PHASE 1: CREATE WAREHOUSE

CREATE WAREHOUSE IF NOT EXISTS RETAIL_P4_WH
WITH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE;

USE WAREHOUSE RETAIL_P4_WH;


-- PHASE 2: CREATE DATABASE AND SCHEMA

CREATE DATABASE IF NOT EXISTS RETAIL_P4_DB;

USE DATABASE RETAIL_P4_DB;

CREATE SCHEMA IF NOT EXISTS RETAIL_P4_SCHEMA;

USE SCHEMA RETAIL_P4_SCHEMA;


-- PHASE 3: CREATE FILE FORMAT

CREATE OR REPLACE FILE FORMAT RETAIL_P4_CSV_FORMAT
TYPE = 'CSV'
FIELD_DELIMITER = ','
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
NULL_IF = ('NULL', 'null', '');


-- PHASE 4: CREATE STAGES

CREATE STAGE IF NOT EXISTS RETAIL_P4_CUSTOMER_STAGE
FILE_FORMAT = RETAIL_P4_CSV_FORMAT;

CREATE STAGE IF NOT EXISTS RETAIL_P4_PRODUCT_STAGE
FILE_FORMAT = RETAIL_P4_CSV_FORMAT;

CREATE STAGE IF NOT EXISTS RETAIL_P4_BRANCH_STAGE
FILE_FORMAT = RETAIL_P4_CSV_FORMAT;

CREATE STAGE IF NOT EXISTS RETAIL_P4_CALENDAR_STAGE
FILE_FORMAT = RETAIL_P4_CSV_FORMAT;

CREATE STAGE IF NOT EXISTS RETAIL_P4_SALES_STAGE
FILE_FORMAT = RETAIL_P4_CSV_FORMAT;


-- PHASE 5: VERIFY STAGES

LIST @RETAIL_P4_SALES_STAGE;


-- PHASE 6: CREATE DIMENSION TABLES

CREATE OR REPLACE TABLE DIM_CUSTOMER (
    CUSTOMER_ID INT PRIMARY KEY,
    CUSTOMER_NAME VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    MEMBERSHIP VARCHAR(20)
);

CREATE OR REPLACE TABLE DIM_PRODUCT (
    PRODUCT_ID INT PRIMARY KEY,
    PRODUCT_NAME VARCHAR(100),
    CATEGORY VARCHAR(50),
    BRAND VARCHAR(50),
    PRICE DECIMAL(10,2)
);

CREATE OR REPLACE TABLE DIM_BRANCH (
    BRANCH_ID INT PRIMARY KEY,
    BRANCH_NAME VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    REGION VARCHAR(30),
    MANAGER_NAME VARCHAR(100)
);

CREATE OR REPLACE TABLE DIM_DATE (
    DATE_ID INT PRIMARY KEY,
    DATE_VALUE DATE,
    DAY INT,
    DAY_NAME VARCHAR(20),
    WEEK_NO INT,
    MONTH VARCHAR(20),
    QUARTER VARCHAR(10),
    YEAR INT,
    IS_WEEKEND VARCHAR(5)
);


-- PHASE 7: CREATE FACT TABLE

CREATE OR REPLACE TABLE FACT_SALES (
    SALE_ID INT PRIMARY KEY,
    CUSTOMER_ID INT,
    PRODUCT_ID INT,
    BRANCH_ID INT,
    DATE_ID INT,
    QUANTITY INT,
    TOTAL_AMOUNT DECIMAL(15,2),
    FOREIGN KEY (CUSTOMER_ID) REFERENCES DIM_CUSTOMER(CUSTOMER_ID),
    FOREIGN KEY (PRODUCT_ID) REFERENCES DIM_PRODUCT(PRODUCT_ID),
    FOREIGN KEY (BRANCH_ID) REFERENCES DIM_BRANCH(BRANCH_ID),
    FOREIGN KEY (DATE_ID) REFERENCES DIM_DATE(DATE_ID)
);


