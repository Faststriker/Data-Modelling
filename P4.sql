-- PHASE 13: VERIFY DATA

SELECT COUNT(*) AS CUSTOMER_COUNT FROM DIM_CUSTOMER;

SELECT COUNT(*) AS PRODUCT_COUNT FROM DIM_PRODUCT;

SELECT COUNT(*) AS BRANCH_COUNT FROM DIM_BRANCH;

SELECT COUNT(*) AS DATE_COUNT FROM DIM_DATE;

SELECT COUNT(*) AS SALES_COUNT FROM FACT_SALES;


-- PHASE 14: CUSTOMER-WISE SALES

SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_SALES
FROM FACT_SALES F
JOIN DIM_CUSTOMER C
ON F.CUSTOMER_ID = C.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
ORDER BY TOTAL_SALES DESC;


-- PHASE 15: PRODUCT-WISE REVENUE

SELECT
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    SUM(F.TOTAL_AMOUNT) AS REVENUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P
ON F.PRODUCT_ID = P.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
ORDER BY REVENUE DESC;


-- PHASE 16: BRANCH-WISE SALES

SELECT
    B.BRANCH_ID,
    B.BRANCH_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_SALES
FROM FACT_SALES F
JOIN DIM_BRANCH B
ON F.BRANCH_ID = B.BRANCH_ID
GROUP BY B.BRANCH_ID, B.BRANCH_NAME
ORDER BY TOTAL_SALES DESC;


-- PHASE 17: MONTHLY REVENUE

SELECT
    D.YEAR,
    D.MONTH,
    SUM(F.TOTAL_AMOUNT) AS MONTHLY_REVENUE
FROM FACT_SALES F
JOIN DIM_DATE D
ON F.DATE_ID = D.DATE_ID
GROUP BY D.YEAR, D.MONTH
ORDER BY D.YEAR, D.MONTH;


-- PHASE 18: STATE-WISE REVENUE

